"""Season Lab: car-development analysis for the Lab tab, from data.js (results, qualifying) and duels.js (qualifying
telemetry: each driver's grid-setting lap, speed trap, minimum speed in every corner).

    python3 tools/build_lab.py      # writes lab.js (window.SEASON.LAB)

Per team and round:
  pace   - best qualifying lap as % slower than the fastest car that day (0 = fastest)
  rank   - pecking-order position by that pace
  trap   - top speed (best of the two cars) minus the fastest trap that day, km/h
  corner - median minimum corner speed vs the second-best car in each corner, km/h, split by corner type
           (slow < 120 km/h, quick >= 120, judged by the reference car's speed there)
Season: points per round, DNFs, average grid and finish.
"""
import json, os, statistics as st

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
S = json.loads(open(os.path.join(ROOT, 'data.js'), encoding='utf-8').read().split('window.SEASON = ', 1)[1].split(';\nwindow.NEWS = ', 1)[0])
D = json.loads(open(os.path.join(ROOT, 'duels.js'), encoding='utf-8').read().split('|| {}, ', 1)[1].rsplit(');', 1)[0])
TEAM = {d['id']: d['team'] for d in S['DRIVERS']}
TEAMS = [t['id'] for t in S['TEAMS']]
rounds = sorted(r['round'] for r in S['RESULTS'])
r1 = lambda x: round(x, 2)

pace, rank, trap, corner = ({t: {} for t in TEAMS} for _ in range(4))
for rd in rounds:
    q = S['QUALI_DETAIL'].get(str(rd), [])
    best = {}
    for x in q:
        if x.get('best'):
            best[x['team']] = min(best.get(x['team'], 1e9), x['best'])
    if best:
        f = min(best.values())
        for i, (t, v) in enumerate(sorted(best.items(), key=lambda kv: kv[1])):
            pace[t][rd] = r1(100 * (v / f - 1)); rank[t][rd] = i + 1
    d = D.get(str(rd))
    if not d:
        continue
    drv = [x for x in d['drivers'] if TEAM.get(x['driver'])]
    traps = {}
    for x in drv:
        traps[TEAM[x['driver']]] = max(traps.get(TEAM[x['driver']], 0), x.get('trap') or 0)
    tmax = max(traps.values())
    for t, v in traps.items():
        trap[t][rd] = r1(v - tmax)
    # corners: best (highest) minimum speed per team in each corner, vs the best team there
    cats = {}
    for c in d['corners']:
        per = {}
        for x in drv:
            v = (x.get('corners') or {}).get(c)
            if v is not None:
                per[TEAM[x['driver']]] = max(per.get(TEAM[x['driver']], 0), v)
        if len(per) < 6:
            continue
        vals = sorted(per.values(), reverse=True)
        top, mid = vals[1], st.median(vals)            # reference = second-best car, so one odd reading can't set it
        if top - mid > 25:                             # flat-out kink or a lap that wasn't pushed: telemetry too noisy here
            continue
        cat = 'slow' if top < 120 else 'fast'
        for t, v in per.items():
            cats.setdefault(t, {}).setdefault(cat, []).append(min(v - top, 0) if v - top < 0 else v - top)
    for t, cs in cats.items():
        corner[t][rd] = {k: r1(st.median(v)) for k, v in cs.items()}

# season results by team
pts = {t: {} for t in TEAMS}; dnf = {t: 0 for t in TEAMS}; grid = {t: [] for t in TEAMS}; fin = {t: [] for t in TEAMS}
for res in S['RESULTS']:
    for x in res['race']:
        t = TEAM.get(x['id'])
        if not t: continue
        pts[t][res['round']] = pts[t].get(res['round'], 0) + (x.get('points') or 0)
        if x.get('grid'): grid[t].append(x['grid'])
        if x.get('pos'): fin[t].append(x['pos'])
        elif x.get('status') != 'DNS': dnf[t] += 1

def phase(series, lo, hi):
    v = [series[r] for r in series if lo <= r <= hi]
    return r1(st.mean(v)) if v else None

n = len(rounds); third = max(1, n // 3)
early, late = (rounds[0], rounds[third - 1]), (rounds[-third], rounds[-1])
teams = {}
for t in TEAMS:
    cp = {}
    for ph, (lo, hi) in (('early', early), ('late', late)):
        cp[ph] = {k: phase({r: corner[t][r][k] for r in corner[t] if k in corner[t][r]}, lo, hi) for k in ('slow', 'fast')}
        cp[ph]['trap'] = phase(trap[t], lo, hi)
        cp[ph]['pace'] = phase(pace[t], lo, hi)
    teams[t] = {'pace': pace[t], 'rank': rank[t], 'trap': trap[t], 'corner': corner[t], 'points': pts[t], 'dnf': dnf[t],
                'grid': r1(st.mean(grid[t])) if grid[t] else None, 'finish': r1(st.mean(fin[t])) if fin[t] else None,
                'phase': cp}
lab = {'rounds': rounds, 'early': list(early), 'late': list(late), 'teams': teams}
out = os.path.join(ROOT, 'lab.js')
with open(out, 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/build_lab.py. Do not edit by hand.\n')
    f.write('window.SEASON.LAB = ' + json.dumps(lab, separators=(',', ':')) + ';\n')
for t in sorted(TEAMS, key=lambda t: teams[t]['phase']['late']['pace'] or 99):
    p = teams[t]['phase']
    print(f"{t:4} pace {p['early']['pace']}% -> {p['late']['pace']}%  trap {p['early']['trap']} -> {p['late']['trap']}  "
          f"slow {p['early']['slow']} -> {p['late']['slow']}  fast {p['early']['fast']} -> {p['late']['fast']}  dnf {teams[t]['dnf']}  grid {teams[t]['grid']} fin {teams[t]['finish']}")
