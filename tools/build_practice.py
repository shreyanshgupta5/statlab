"""Builds practice.js (window.PRACTICE): practice results and long-run pace for a race weekend, from OpenF1.

    python3 tools/build_practice.py 22

Per practice session: each driver's best lap and lap count, red flags, and (for every session) long runs: stints with
8+ representative laps, scored by the median of laps within 4% of that stint's best (drops in/out laps and traffic). Run it again
after each session; sessions that have not run yet are skipped.
"""
import json, os, sys, time, statistics, urllib.request, urllib.parse
from datetime import datetime, timezone

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UA = {'User-Agent': 'statlab-app/1.0 (fan project)'}

def get(ep, **q):
    url = 'https://api.openf1.org/v1/%s?%s' % (ep, urllib.parse.urlencode(q))
    for i in range(5):
        try:
            time.sleep(0.4)
            return json.load(urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60))
        except urllib.error.HTTPError as e:
            if e.code == 404:
                return []
            print('  retry', e, file=sys.stderr); time.sleep(3 + 3 * i)
        except Exception as e:
            print('  retry', e, file=sys.stderr); time.sleep(3 + 3 * i)
    raise SystemExit('failed: ' + url)

def season():
    text = open(os.path.join(ROOT, 'data.js'), encoding='utf-8').read()
    return json.loads(text.split('window.SEASON = ', 1)[1].split(';\nwindow.NEWS', 1)[0])

def session(key):
    drv = {d['driver_number']: d for d in get('drivers', session_key=key)}
    laps, stints, rc = get('laps', session_key=key), get('stints', session_key=key), get('race_control', session_key=key)
    best, count = {}, {}
    for l in laps:
        n = l['driver_number']; count[n] = count.get(n, 0) + 1
        if l.get('lap_duration') and not l.get('is_pit_out_lap'):
            best[n] = min(best.get(n, 1e9), l['lap_duration'])
    order = sorted(best, key=best.get)
    code = lambda n: drv[n]['name_acronym'] if n in drv else str(n)
    names = {code(n): drv[n].get('last_name') or drv[n].get('full_name', '') for n in drv}
    runs = []
    for s in stints:
        if s.get('lap_end') is None or s['lap_end'] - s['lap_start'] < 7:
            continue
        ls = [l['lap_duration'] for l in laps if l['driver_number'] == s['driver_number'] and s['lap_start'] < l['lap_number'] <= s['lap_end']
              and l.get('lap_duration') and not l.get('is_pit_out_lap')]
        if len(ls) < 6:
            continue
        b = min(ls); good = [x for x in ls if x < b * 1.04]
        if len(good) >= 8:
            runs.append([code(s['driver_number']), s.get('compound') or '', round(statistics.median(good), 3), len(good)])
    best_run = {}
    for r in sorted(runs, key=lambda r: r[2]):
        best_run.setdefault(r[0], r)   # each driver's quickest long run
    return {
        'best': [[code(n), round(best[n], 3), count.get(n, 0)] for n in order],
        'redFlags': sum(1 for r in rc if r.get('message', '').startswith('RED FLAG')),
        'longRuns': sorted(best_run.values(), key=lambda r: r[2]),
        'names': names,
    }

def main():
    S = season(); out = {}
    path = os.path.join(ROOT, 'practice.js')
    if os.path.exists(path):
        out = json.loads(open(path, encoding='utf-8').read().split('window.PRACTICE = ', 1)[1].rstrip().rstrip(';'))
    now = datetime.now(timezone.utc)
    for rnd in map(int, sys.argv[1:]):
        race = next(c for c in S['CALENDAR'] if c['round'] == rnd)
        year = int(race['date'][:4]); start = race['sessions'][0]['start'][:10]
        sess = [s for s in get('sessions', year=year) if s['session_type'] == 'Practice' and start <= s['date_start'][:10] <= race['date']]
        done = []
        for s in sorted(sess, key=lambda s: s['date_start']):
            if datetime.fromisoformat(s['date_end']) > now:
                continue
            d = session(s['session_key']); d['name'] = s['session_name']; d['start'] = s['date_start']
            done.append(d); print(rnd, s['session_name'], len(d['best']), 'drivers,', len(d['longRuns']), 'long runs')
        out[str(rnd)] = {'sessions': done}
    with open(path, 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/build_practice.py (OpenF1). Do not edit by hand.\n')
        f.write('window.PRACTICE = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')

if __name__ == '__main__':
    main()
