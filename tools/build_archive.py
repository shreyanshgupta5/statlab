"""Builds archive.js (window.ARCHIVE): every past F1 season for the Archive tab, from Jolpica (Ergast).

    python3 tools/build_archive.py            # 1950 to last year (skips seasons already in the file)
    python3 tools/build_archive.py 2025       # just one season (replaces it)

Per season: rounds, final top 3 drivers (points, wins, team), constructors' top 3 (from 1958), and every race winner,
which gives wins per driver and team, different winners, and wins from pole.
"""
import json, os, sys, time, urllib.request, urllib.error
from datetime import date

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UA = {'User-Agent': 'statlab-app/1.0 (fan project)'}
API = 'https://api.jolpi.ca/ergast/f1/'

def get(path):
    for i in range(6):
        try:
            time.sleep(1.1)
            return json.load(urllib.request.urlopen(urllib.request.Request(API + path, headers=UA), timeout=60))['MRData']
        except urllib.error.HTTPError as e:
            print('  retry', e.code, path, file=sys.stderr); time.sleep(5 + 5 * i)
        except Exception as e:
            print('  retry', e, path, file=sys.stderr); time.sleep(5 + 5 * i)
    raise SystemExit('failed: ' + path)

def code(d):
    return d.get('code') or ''.join(ch for ch in d['familyName'].upper() if ch.isalpha())[:3]

def season(y):
    ds = get(f'{y}/driverStandings/?limit=3')['StandingsTable']['StandingsLists']
    if not ds:
        return None
    top = [{'n': x['Driver']['givenName'] + ' ' + x['Driver']['familyName'], 'last': x['Driver']['familyName'], 'c': code(x['Driver']),
            'nat': x['Driver'].get('nationality', ''), 'pts': float(x['points']), 'w': int(x['wins']),
            'team': x['Constructors'][0]['name'] if x.get('Constructors') else ''} for x in ds[0]['DriverStandings']]
    cons = []
    if y >= 1958:
        cs = get(f'{y}/constructorStandings/?limit=3')['StandingsTable']['StandingsLists']
        if cs:
            cons = [{'n': x['Constructor']['name'], 'pts': float(x['points']), 'w': int(x['wins'])} for x in cs[0]['ConstructorStandings']]
    races = get(f'{y}/results/1/?limit=100')['RaceTable']['Races']
    wins, twins, pole = {}, {}, 0
    for r in races:
        w = r['Results'][0]
        k = w['Driver']['familyName']; wins[k] = wins.get(k, 0) + 1
        t = w['Constructor']['name']; twins[t] = twins.get(t, 0) + 1
        if w.get('grid') == '1':
            pole += 1
    return {'y': y, 'rounds': int(ds[0]['round']), 'top': top, 'cons': cons,
            'wins': sorted(([k, v] for k, v in wins.items()), key=lambda x: -x[1]),
            'teamWins': sorted(([k, v] for k, v in twins.items()), key=lambda x: -x[1]), 'fromPole': pole}

def main():
    path = os.path.join(ROOT, 'archive.js')
    out = {}
    if os.path.exists(path):
        out = json.loads(open(path, encoding='utf-8').read().split('window.ARCHIVE = ', 1)[1].rstrip().rstrip(';'))
    years = list(map(int, sys.argv[1:])) or [y for y in range(1950, date.today().year) if str(y) not in out]
    for y in years:
        s = season(y)
        if s:
            out[str(y)] = s
            print(y, s['top'][0]['last'], s['top'][0]['team'], len(s['wins']), 'winners', flush=True)
            with open(path, 'w', encoding='utf-8') as f:   # save as we go: the API is slow and rate-limited
                f.write('// Generated by tools/build_archive.py (Jolpica). Do not edit by hand.\n')
                f.write('window.ARCHIVE = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')

if __name__ == '__main__':
    main()
