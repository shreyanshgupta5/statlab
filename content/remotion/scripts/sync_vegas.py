"""Copies the approved 'Who wins Vegas?' graphics into the Remotion project.
Reads ../explained/who-wins-vegas.html (built by explained/build-who-wins.py) and writes
  src/vegas/legacy.js  - data, chapter list (CH/T0), graphics G[] and their animations A[] as an ES module
  src/vegas/styles.js  - the page CSS
Run after changing the explainer:  python3 scripts/sync_vegas.py"""
import os, re
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
html = open(os.path.join(R, "..", "explained", "who-wins-vegas.html")).read()
css = html[html.index("<style>") + 7:html.index("</style>")]
js = html[html.index("<script>") + 8:html.rindex("</script>")]
head = js[:js.index("/* ===================== build ===================== */")]
head = re.sub(r'^const MODE = .*\n', "", head, flags=re.M)
head = re.sub(r'^document\.getElementById\("stage"\)\.className = .*\n', "", head, flags=re.M)
anim = js[js.index("const A = ["):js.index("async function renderSoundtrack")]
out = ("// @ts-nocheck\n// GENERATED by scripts/sync_vegas.py from explained/who-wins-vegas.html. Do not edit here.\n"
       + head
       + "const $ = (id) => document.getElementById(id), op = (el, v) => el && el.setAttribute(\"opacity\", v), all = (sel) => [...document.querySelectorAll(sel)];\n"
       + anim
       + "export { CH, T0, DURATION, XF, G, A, rnd, clamp, easeOut, easeIn, easeInOut, back };\n")
open(os.path.join(R, "src", "vegas", "legacy.js"), "w").write(out)
open(os.path.join(R, "src", "vegas", "styles.js"), "w").write("// GENERATED by scripts/sync_vegas.py\nexport const CSS = " + repr(css).replace("\\n", "\\n") + ";\n")
print("legacy.js", len(out), "bytes · styles.js", len(css), "bytes")
